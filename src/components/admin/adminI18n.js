export function normalizeAdminLanguage(language) {
  return language === "en" ? "en" : "vi"
}

export function getAdminText(language, key, params = {}) {
  const lang = normalizeAdminLanguage(language)
  const template = ADMIN_TEXT[lang]?.[key] ?? ADMIN_TEXT.vi[key] ?? key
  return String(template).replace(/\{(\w+)\}/g, (_, token) =>
    params[token] !== undefined && params[token] !== null ? String(params[token]) : "",
  )
}

